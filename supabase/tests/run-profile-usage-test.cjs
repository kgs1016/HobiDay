const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
(async () => {
  const db = new PGlite();
  const member='11111111-1111-4111-8111-111111111111', other='22222222-2222-4222-8222-222222222222', admin='33333333-3333-4333-8333-333333333333', idle='44444444-4444-4444-8444-444444444444';
  const as = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); await db.exec('set role authenticated'); };
  const record = (id,event='profile_opened',error=null) => db.query('select record_profile_usage($1,$2,$3,$4,$5) as ok',[id,event,'ios','1.1.1',error]);
  const report = async onlyNew => (await db.query('select admin_profile_usage(7,$1) as report',[onlyNew])).rows[0].report;
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key, created_at timestamptz default now(),deleted_at timestamptz,is_anonymous boolean default false);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth to authenticated;
      create table public.app_admins(user_id uuid primary key);
      create function is_app_admin() returns boolean language sql stable security definer set search_path=public as $$ select exists(select 1 from app_admins where user_id=auth.uid()) $$;
      revoke all on function is_app_admin() from public,anon,authenticated;`);
    await db.query('insert into auth.users(id,created_at) values($1,now()),($2,now()-interval \'10 days\'),($3,now()-interval \'40 days\'),($4,now())',[member,other,admin,idle]);
    await db.query('insert into app_admins values($1)',[admin]);
    await db.exec(fs.readFileSync(path.join(__dirname,'../migrations/20260916160000_profile_usage.sql'),'utf8'));
    await db.exec('set role anon'); await assert.rejects(record(member),/permission denied/);
    await as(''); assert.equal((await record(member)).rows[0].ok,false);
    await as(member);
    await assert.rejects(db.query('select * from profile_usage_events'),/permission denied/);
    await assert.rejects(db.query("insert into profile_usage_events(user_id,id,event,platform) values($1,$2,'profile_opened','web')",[other,member]),/permission denied/);
    assert.equal((await report(true)).error,'not_admin');
    await record(member); await record(member); await record(other); await record(admin,'profile_saved');
    await assert.rejects(record(idle,'an email address'),/check constraint/);
    await assert.rejects(record(idle,'profile_save_failed','user private text'),/check constraint/);
    await assert.rejects(db.query('select purge_profile_usage()'),/permission denied/);
    await as(other); await record(member);
    await as(admin);
    const data=await report(true);
    assert.equal(data.cohort_count,2); assert.equal(data.observed_users,1);
    assert.deepEqual(data.stages.find(s=>s.event==='profile_opened'),{event:'profile_opened',users:1,events:2});
    assert.equal(data.recent_users.find(u=>u.user_id===idle).last_event,null,'no event does not imply no app use');
    assert.equal((await report(false)).cohort_count,2,'existing member is separate from new signup cohort');
    await db.exec('reset role');
    assert.equal((await db.query('select count(*)::int as n from profile_usage_events where user_id=$1',[member])).rows[0].n,3,'duplicate id cannot inflate counts');
    await as(member);
    await db.query("select record_profile_usage(gen_random_uuid(),'profile_ready','web') from generate_series(1,70)");
    await db.exec('reset role');
    assert.equal((await db.query('select count(*)::int as n from profile_usage_events where user_id=$1',[member])).rows[0].n,60,'server rate limit');
    await db.query("insert into profile_usage_events(user_id,id,event,platform,created_at) values($1,gen_random_uuid(),'profile_opened','web',now()-interval '91 days')",[other]);
    await db.exec('select purge_profile_usage()');
    assert.equal((await db.query("select count(*)::int as n from profile_usage_events where created_at<now()-interval '90 days'")).rows[0].n,0);
    await db.query('delete from auth.users where id=$1',[member]);
    assert.equal((await db.query('select count(*)::int as n from profile_usage_events where user_id=$1',[member])).rows[0].n,0,'account deletion removes usage data');
    console.log('PASS profile usage SQL: auth ownership, anon/non-admin denial, idempotency, unique-user cohorts, no-record members, input allowlist, rate limit, retention and deletion');
  } finally { await db.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
