-- ═══════════════════════════════════════════════════════════════
--  프로필 레벨을 선택 입력으로 — not null 해제
-- ═══════════════════════════════════════════════════════════════
-- 레벨은 자기신고 값인데 필수라서, 감을 못 잡은 사람이 아무 값이나 찍고
-- 지나갔다. 비워둘 수 있게 한다. 값을 채우면 1~5 검사는 그대로 남는다.
--
-- 프로필 완성 판정(claim_profile_bonus: 사진·구력)과 사람 찾기 조회는
-- 레벨을 보지 않아서 이 한 줄로 끝난다. 화면은 레벨이 없으면 그 칸을
-- 접는다 (web 쪽을 같이 바꿨다).

alter table profiles alter column level drop not null;
