#!/usr/bin/env node
// 운영 DB에 연결하지 않는다. 로컬 시안과 동일한 콘텐츠의 일괄 반영 SQL만 만든다.
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../web/src/content/editorial-2026-09-09.json", import.meta.url);
const destination = new URL("../supabase/content/20260910_news_images.sql", import.meta.url);
const content = JSON.parse(fs.readFileSync(source, "utf8"));
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const ids = new Set();
for (const item of content.news) {
  if (!uuid.test(item.id) || ids.has(item.id)) throw new Error("invalid/duplicate content ID");
  ids.add(item.id);
  const text = item.summary ?? item.body;
  if (!text || [...text].length > (item.summary ? 2000 : 3000)) throw new Error(`content length: ${item.id}`);
  if (!item.title || [...item.title].length > (item.summary ? 200 : 80)) throw new Error(`title length: ${item.id}`);
}
if (!uuid.test(content.operator_id)) throw new Error("invalid operator ID");
content.news = content.news.map(item => {
  if (!/^\/images\/news\/[a-z-]+-v1\.webp$/.test(item.image_url)) throw new Error('invalid news asset');
  if (!fs.existsSync(new URL('../web/public' + item.image_url, import.meta.url))) throw new Error('missing news asset');
  return {...item, image_url: 'https://hobiday-eight.vercel.app' + item.image_url};
});
delete content.gear;
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const sql = `-- Generated by node scripts/prepare-editorial.mjs. Edit the source JSON, then regenerate.
-- Sources and fact-check date: web/src/content/editorial-2026-09-09.json
-- Run during the next authorized batch release, with the corresponding news image assets.
-- Existing news IDs, visibility, source links, and original publication dates are preserved.
begin;
create temporary table hobiday_editorial_payload (value jsonb) on commit drop;
insert into hobiday_editorial_payload values (${quote(JSON.stringify(content))}::jsonb);

do $$
declare payload jsonb; expected int; matched int;
begin
  select value into payload from hobiday_editorial_payload;
  if not exists (select 1 from public.profiles where id = (payload->>'operator_id')::uuid and nickname = '운영팀') then
    raise exception 'Expected 운영팀 profile is missing; no content was changed';
  end if;
  expected := jsonb_array_length(payload->'news');
  select count(*) into matched
    from jsonb_to_recordset(payload->'news') as n(id uuid, external_id text, url text)
    join public.community_articles a on a.id = n.id and a.external_id = n.external_id and a.url = n.url and a.kind = 'news';
  if matched <> expected then
    raise exception 'Published news differs from the reviewed source set; no content was changed';
  end if;
end $$;

update public.community_articles a
   set title = n.title, summary = n.summary, image_url = n.image_url, updated_at = now()
  from hobiday_editorial_payload e,
       jsonb_to_recordset(e.value->'news') as n(id uuid, title text, summary text, image_url text)
 where a.id = n.id and (a.title is distinct from n.title or a.summary is distinct from n.summary or a.image_url is distinct from n.image_url);

-- Existing gear posts are preserved while the section is temporarily hidden.
commit;
`;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(destination, "utf8") !== sql) throw new Error("Editorial SQL is stale; run node scripts/prepare-editorial.mjs");
  console.log("PASS: editorial SQL matches the preview content");
} else {
  fs.mkdirSync(new URL("../supabase/content/", import.meta.url), { recursive: true });
  fs.writeFileSync(destination, sql);
  console.log(`Prepared ${content.news.length} news updates with AI images: ${fileURLToPath(destination)}`);
}
